"""Build switch/paidsafe.template.yaml from agents/instructions/*.md, validate it with the Switch Gateway,
and (with --save) save it to the server so it shows in Switch Console → Templates.

    python scripts/build_template.py            # build + validate
    python scripts/build_template.py --save     # also save to the server's template list
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.error
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "switch" / "paidsafe.template.yaml"

ROOM_INSTRUCTIONS = """PaidSafe room for one late-paying client. People and agents decide together whether to chase or wait.
- Ledger (no LLM) posts numbered fact cards F1..F6 and fact-checks every debate post. Uncited or wrong numbers get a ❌.
- Relationship and Cash debate for at most 2 rounds. Every number must cite a fact card like [F3].
- Only the verified Owner opens a debate and picks an option (approve A-D). Only the verified Accountant approves numbers.
  The Warden checks the Switch sender id on every approval. Display names are ignored.
- Kill switch: '@warden stopall' freezes every side-effecting tool. '@warden resume' must come from the OTHER human.
- All data is synthetic. Payments and sends are simulated. Not legal or financial advice."""

HEADER = """# PaidSafe: Switch group template (format version 1, Switch 0.31).
# Creates the two LLM debaters as managed agents and the client room with all four agents and both humans.
# Ledger and Warden are custom agent-protocol agents: register them first with
#   python scripts/register_agents.py
# Generated by scripts/build_template.py from agents/instructions/*.md. Edit those, not this file.
"""


def build() -> dict:
    instr = lambda n: (ROOT / "agents" / "instructions" / f"{n}.md").read_text(encoding="utf-8")  # noqa: E731
    common = {"provider": "claude", "machine": "{machine}", "addressing": "owner-agents", "allow_existing": True}
    return {
        "version": 1,
        "params": {
            "room": {"type": "string", "label": "Room (one per client)", "default": "client-megamart"},
            "bridge": {"type": "bridge", "default": ["$first"]},
            "machine": {"type": "machine", "default": ["$first"], "input": "advanced"},
            "accountant": {"type": "string", "label": "Accountant's username", "default": "accountant"},
        },
        "agents": [
            {"name": "relationship", "display_name": "relationship",
             "description": "Debater: argues to keep the client relationship",
             "directory": "{$agents_dir}/relationship", "model": "claude-opus-5-5",
             "instructions": instr("relationship"), **common},
            {"name": "cash", "display_name": "cash",
             "description": "Debater: argues to get paid now (cash flow, statutory rights)",
             "directory": "{$agents_dir}/cash", "model": "claude-sonnet-5-5",
             "instructions": instr("cash"), **common},
        ],
        "room": {
            "name": "{room}",
            "description": "PaidSafe: chase-or-wait decisions on a late client invoice, with verified human approvals",
            "instructions": ROOM_INSTRUCTIONS,
            "bridge": "{bridge}",
            "channel_type": "channel_public",
            "agents": ["relationship", "cash", "ledger", "warden"],
            "users": ["{$creator}", "{accountant}"],
            "docs": [{
                "name": "client-playbook",
                "description": "What we decided for this client before, and how it went",
                "instructions": "Append one line per decision: date, invoice, option, reason, outcome.",
                "content": "# Client playbook\n\n(no decisions yet)\n",
            }],
        },
        "kickoff": ("PaidSafe room ready. Owner: type `@ledger MegaMart invoice INV-1042 is late. Chase or wait?` "
                    "to start. Kill switch: `@warden stopall`."),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--save", action="store_true")
    ap.add_argument("--no-validate", action="store_true")
    a = ap.parse_args()
    text = HEADER + yaml.safe_dump(build(), sort_keys=False, allow_unicode=True, width=110)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    if a.no_validate:
        return

    from agents.switch_client import base_url, http
    from scripts.register_agents import console_admin_opener
    base = base_url()
    opener = console_admin_opener(base)
    try:
        res = http("POST", f"{base}/gateway/templates/validate", {"content": text}, opener=opener)
        print(json.dumps(res, indent=2)[:1500])
        if a.save:
            saved = http("POST", f"{base}/gateway/templates",
                         {"name": "PaidSafe client room", "kind": "group", "content": text,
                          "description": "Chase-or-wait debate room with fact cards, verified approvals and a kill switch"},
                         opener=opener)
            print("saved template", saved.get("id"))
    except urllib.error.HTTPError as e:
        sys.exit(f"{e.code}: {e.read().decode()[:1500]}")


if __name__ == "__main__":
    main()
